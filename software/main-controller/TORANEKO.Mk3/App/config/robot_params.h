/*
 * robot_params.h
 * 機体の定数（制御周期、タイヤ径、ギア比、トレッド幅など）
 *
 * 制御周期、電池の下限、タイヤの直径。ほかの値（トレッド幅など）は、使うときに足す。
 */
#ifndef CONFIG_ROBOT_PARAMS_H
#define CONFIG_ROBOT_PARAMS_H

/* 制御周期 [Hz]（README の決定事項）。制御の処理（ログの記録も）は 1 秒にこの回数呼ばれる */
#define CTRL_FREQ_HZ 2000
/* 制御周期 [s]（1 ÷ 2000 = 0.0005 秒 = 0.5ms） */
#define CTRL_PERIOD_S (1.0f / CTRL_FREQ_HZ)

/* 電池の下限の電圧 [V]。電源を入れたときにこれより低ければ、何もせずに知らせる（MODES.md の 2-1）。
 * 2 セルのリポで、1 セル 3.75V（2026-10-22 に作者が決めた） */
#define BATTERY_LOW_V 7.5f

/* タイヤの直径 [mm]。モード6 No.1（直進）で、走った距離をものさしで測って合わせる。
 * 2026-10-24：14.0mm で 360mm 走らせたら 365mm 進んだ（ここから出すと 14.19mm）。
 * 14.2mm にしたら 363mm 進んだ（ここから出すと 14.32mm）。14.25mm でも 363mm 進んだ（14.37mm）。
 * 作者が 14.3mm に決めた。
 * 2026-11-03：14.3mm で 280mm 走らせたら（モード6 No.1、吸引なし）、2 回とも 287mm 進んだ（7mm 多い）。
 * 14.3 × 287 ÷ 280 = 14.66mm にした。14.66mm で走らせたら 281mm 進んだ（1mm 多い）ので、
 * 14.66 × 281 ÷ 280 = 14.71mm にした。
 * ところが、ここまでは目標の 280mm と比べていたが、エンコーダで測った距離（RESULT の encoder）は 280mm より
 * 短かった（止まる前に、摩擦でずれが残っていた。14.71mm の直進で encoder 273.3mm）。ものさしの距離を encoder と
 * 比べると、どの走り方でも 1.05 倍（14.3mm のとき）・1.024 倍（14.71mm のとき）多く進んでいて、
 * 吸引あり・なしで同じだった（吸引で多く進むわけではなかった）。
 *   14.3 × 295 ÷ 281.2 = 15.00（吸引あり）、14.71 × 288 ÷ 281.4 = 15.05（吸引あり）、14.71 × 280 ÷ 273.3 = 15.07（吸引なし）
 * なので 15.05mm にした。これからは「新しい直径 = 今の直径 × ものさしの距離 ÷ encoder の距離」で直す。
 * 15.05mm にして（摩擦の分も足して）走らせたら、吸引なしの直進でぴったり 280mm、吸引ありの加速度テスト（4000mm/s²）で
 * 281mm だった */
#define TIRE_DIAMETER_MM 15.05f

/* トレッド幅 [mm]（左右のタイヤのまん中どうしの間隔）。基板の配置図（hardware/kicad/TORANEKO.Mk3 の
 * 配置ガイド_メイン基板.dxf）で、左右のベアリングの組のまん中が 0mm と 25mm にあることから。
 * その場旋回のフィードフォワードに使う（向きはジャイロで測るので、少しずれていても回る角度は変わらない） */
#define TREAD_MM 25.0f

/* 機体の重さ [g]（電池を含む。グリップの上限の見積もりに使う。sys/shortest.c） */
#define ROBOT_MASS_G 26.0f

/* ギア比（41T ÷ 11T ≒ 3.73）は、ここには置かない。エンコーダはタイヤの軸に付いているので、
 * 距離の計算にギア比は要らない */

#endif /* CONFIG_ROBOT_PARAMS_H */
