/*
 * ctrl_gains.h
 * 速度と角度の制御の係数（ctrl/control.c が使う）
 *
 * モーターにかける電圧 [V] を、次の 2 つを足して決める（ctrl/control.c の先頭のコメント）。
 *   フィードフォワード：目標の速さ・加速度から「これくらいかければ、その速さになるはず」という電圧
 *   フィードバック    ：目標と、測った速さ・角度とのずれを小さくする電圧
 * 値はどれも、まず走らせてみるための最初の値。走行ログを見ながら合わせる。
 */
#ifndef CONFIG_CTRL_GAINS_H
#define CONFIG_CTRL_GAINS_H

/* ---- フィードフォワード（前に進む分） ---- */

/* 速さ 1mm/s あたりの電圧 [V/(mm/s)]。
 * 2026-10-22 のエンコーダの歪みの測定（タイヤを浮かせて回した）で、1.0V でタイヤ 26.9 回転/秒、
 * 2.0V で 53.4 回転/秒だった。タイヤ 1 周 44.0mm をかけると、1V で約 1180mm/s なので、1 ÷ 1180 */
#define FF_SPEED_V_PER_MM_S 0.000845f

/* 加速度 1mm/s² あたりの電圧 [V/(mm/s²)]。機体の重さとモーターの値からの見積もり（仮）。
 * 加速するところで速さが目標より遅れるなら大きくし、先に行くなら小さくする */
#define FF_ACCEL_V_PER_MM_S2 0.00007f

/* 動き出すのに要る電圧 [V]（床との摩擦の分。仮に 0）。走らせて、速さがずっと目標より遅れるなら足す */
#define FF_FRICTION_V 0.0f

/* その場旋回で、摩擦に負けないために足す電圧 [V]（タイヤ 1 つあたり）。
 * 2026-10-24 のその場 180° 旋回のログで、720deg/s のあいだ左右に約 0.4V かけていた（摩擦がなければ 0.13V で足りる）。
 * 止まったあとも 0.2V では動けず、167° で止まった。摩擦を約 0.25V とした計算で同じように止まったので、
 * 少し少なめの 0.2V にする（多すぎると、回りすぎる） */
#define FF_TURN_FRICTION_V 0.2f

/* ---- フィードバック（速さ） ---- */

/* 速さのずれ 1mm/s あたりの電圧 [V/(mm/s)]（P）。
 * 1V で進む速さが KOGUMA（約 340mm/s）の約 3.5 倍なので、KOGUMA の係数を 3.5 で割り、さらに半分から始める */
#define SPEED_KP 0.003f

/* 位置のずれ（速さのずれを足し合わせたもの）1mm あたりの電圧 [V/mm]（I）。決め方は SPEED_KP と同じ */
#define SPEED_KI 0.03f

/* ---- フィードバック（向き） ---- */

/* 角速度のずれ 1deg/s あたりの電圧 [V/(deg/s)]（P）。左右のモーターに、+ と - で逆向きにかける。
 * 2026-10-24 のその場旋回で、目標に約 30deg/s 遅れたままだったので 2 倍にした（0.0015 → 0.003） */
#define OMEGA_KP 0.003f

/* 角度のずれ（角速度のずれを足し合わせたもの）1deg あたりの電圧 [V/deg]（I）。
 * 同じ旋回で、13° ずれても 0.2V にしかならず、摩擦に負けて止まったので、約 3 倍にした（0.015 → 0.05） */
#define ANGLE_KI 0.05f

/* ---- 横の壁に沿って走る補正（直進のときだけ） ---- */

/* 横の壁からのずれ 1 あたり（センサの値の差）、目標の角速度をどれだけ曲げるか [deg/s]（P）。
 * 壁から 1mm 寄るとセンサの値の差が約 290 変わる（2026-10-22 の測定から、おおよその見積もり）ので、
 * 1mm で約 15deg/s 曲げる */
#define WALL_KP 0.05f

/* ずれの変わる速さ 1/s あたり、目標の角速度をどれだけ曲げるか [deg/s]（D）。
 * P だけだと、まん中を通りすぎて左右にゆれ続けるので、ずれが小さくなっていく速さで曲げ方を弱める。
 * 300mm/s で、ゆれが早く収まるように計算した値（減衰比 0.7） */
#define WALL_KD 0.008f

/* 補正で曲げる角速度の上限 [deg/s] */
#define WALL_OMEGA_LIMIT_DEG_S 90.0f

/* これより遅いときは補正しない [mm/s]（止まる直前・走り出しは、センサの値が目標から離れていても気にしない） */
#define WALL_CONTROL_MIN_SPEED_MM_S 100.0f

/* ---- 止める条件（フェイルセーフ） ---- */

/* 位置のずれがこれより大きくなったら止める [mm]（ぶつかった、タイヤが空回りした、など） */
#define POSITION_ERROR_LIMIT_MM 30.0f

/* 角度のずれがこれより大きくなったら止める [deg]（モーターの向きが逆、ぶつかって向きが変わった、など） */
#define ANGLE_ERROR_LIMIT_DEG 30.0f

#endif /* CONFIG_CTRL_GAINS_H */
