/*
 * ctrl_gains.h
 * 速度と角度の制御の係数（ctrl/control.c が使う）
 *
 * モーターにかける電圧 [V] を、次の 2 つを足して決める（ctrl/control.c の先頭のコメント）。
 *   フィードフォワード：目標の速さ・加速度から「これくらいかければ、その速さになるはず」という電圧
 *   フィードバック    ：目標と、測った速さ・角度とのずれを小さくする電圧
 * 値はどれも、まず走らせてみるための最初の値。走行ログを見ながら合わせる。
 */
#ifndef CONFIG_CTRL_GAINS_H
#define CONFIG_CTRL_GAINS_H

/* ---- フィードフォワード（前に進む分） ---- */

/* 速さ 1mm/s あたりの電圧 [V/(mm/s)]。
 * 2026-10-22 のエンコーダの歪みの測定（タイヤを浮かせて回した）で、1.0V で 317mm/s、2.0V で 630mm/s だった
 * （モーター 26.9 回転/秒 ÷ ギア比 3.73 × タイヤ 1 周 44.0mm）。1V で約 315mm/s なので、1 ÷ 315 */
#define FF_SPEED_V_PER_MM_S 0.00317f

/* 加速度 1mm/s² あたりの電圧 [V/(mm/s²)]。機体の重さとモーターの値からの見積もり（仮）。
 * 加速するところで速さが目標より遅れるなら大きくし、先に行くなら小さくする */
#define FF_ACCEL_V_PER_MM_S2 0.00002f

/* 動き出すのに要る電圧 [V]（床との摩擦の分。仮に 0）。走らせて、速さがずっと目標より遅れるなら足す */
#define FF_FRICTION_V 0.0f

/* ---- フィードバック（速さ） ---- */

/* 速さのずれ 1mm/s あたりの電圧 [V/(mm/s)]（P）。KOGUMA の約半分から始める */
#define SPEED_KP 0.01f

/* 位置のずれ（速さのずれを足し合わせたもの）1mm あたりの電圧 [V/mm]（I）。KOGUMA の約半分から始める */
#define SPEED_KI 0.1f

/* ---- フィードバック（向き） ---- */

/* 角速度のずれ 1deg/s あたりの電圧 [V/(deg/s)]（P）。左右のモーターに、+ と - で逆向きにかける */
#define OMEGA_KP 0.005f

/* 角度のずれ（角速度のずれを足し合わせたもの）1deg あたりの電圧 [V/deg]（I） */
#define ANGLE_KI 0.05f

/* ---- 止める条件（フェイルセーフ） ---- */

/* 位置のずれがこれより大きくなったら止める [mm]（ぶつかった、タイヤが空回りした、など） */
#define POSITION_ERROR_LIMIT_MM 30.0f

/* 角度のずれがこれより大きくなったら止める [deg]（モーターの向きが逆、ぶつかって向きが変わった、など） */
#define ANGLE_ERROR_LIMIT_DEG 30.0f

#endif /* CONFIG_CTRL_GAINS_H */
