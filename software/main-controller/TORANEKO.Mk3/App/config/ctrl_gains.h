/*
 * ctrl_gains.h
 * 速度と角度の制御の係数（ctrl/control.c が使う）
 *
 * モーターにかける電圧 [V] を、次の 2 つを足して決める（ctrl/control.c の先頭のコメント）。
 *   フィードフォワード：目標の速さ・加速度から「これくらいかければ、その速さになるはず」という電圧
 *   フィードバック    ：目標と、測った速さ・角度とのずれを小さくする電圧
 * 値はどれも、まず走らせてみるための最初の値。走行ログを見ながら合わせる。
 */
#ifndef CONFIG_CTRL_GAINS_H
#define CONFIG_CTRL_GAINS_H

/* ---- フィードフォワード（前に進む分） ---- */

/* 速さ 1mm/s あたりの電圧 [V/(mm/s)]。
 * 2026-10-22 のエンコーダの歪みの測定（タイヤを浮かせて回した）で、1.0V でタイヤ 26.9 回転/秒、
 * 2.0V で 53.4 回転/秒だった。タイヤ 1 周 44.0mm をかけると、1V で約 1180mm/s なので、1 ÷ 1180 */
#define FF_SPEED_V_PER_MM_S 0.000845f

/* 加速度 1mm/s² あたりの電圧 [V/(mm/s²)]。機体の重さとモーターの値からの見積もり（仮）。
 * 加速するところで速さが目標より遅れるなら大きくし、先に行くなら小さくする */
#define FF_ACCEL_V_PER_MM_S2 0.00007f

/* 動き出すのに要る電圧 [V]（床との摩擦の分）。2026-11-03 の吸引なしの直進・加速度テストのログで、
 * かけた電圧を「速さの分 + 加速度の分 + 摩擦の分」に分けると、摩擦の分は 0.14〜0.16V だった
 * （0 のままだと、直進で止まる位置がエンコーダで 7mm 手前になっていた）。0.15V にする */
#define FF_FRICTION_V 0.15f

/* 吸引しているとき（吸引ファンの電圧が 0 より大きいとき）に、FF_FRICTION_V に足す電圧 [V]（前に進む分）。
 * 吸引で機体が床に押しつけられると、転がりにくさ（摩擦）が増える。2026-11-03 の吸引ありの加速度テスト
 * （logs/20261103-215358_session.txt）では、
 *   - どの加速度でも、止まる位置が目標の 280mm より 10mm 手前だった（止まる前のずれを直す約 0.3V では動き出せない）
 *   - 走っているあいだも、速さが目標より 70〜150mm/s 遅れていた
 * 滑らなかった 4000〜10000mm/s² の 4 回で、かけた電圧を「速さの分 + 加速度の分 + 摩擦の分」に分けて求めると、
 * 摩擦の分は 0.41〜0.49V だった（0.4V を足したあとの走りでも 0.44V）。そのうち 0.15V は吸引なしでもある
 * 摩擦（FF_FRICTION_V）なので、吸引で増える分は 0.3V にする（合わせて 0.45V） */
#define FF_SUCTION_FRICTION_V 0.3f

/* その場旋回で、摩擦に負けないために足す電圧 [V]（タイヤ 1 つあたり）。
 * 2026-10-24 のその場 180° 旋回のログで、720deg/s のあいだ左右に約 0.4V かけていた（摩擦がなければ 0.13V で足りる）。
 * 止まったあとも 0.2V では動けず、167° で止まった。摩擦を約 0.25V とした計算で同じように止まったので、
 * 少し少なめの 0.2V にする（多すぎると、回りすぎる） */
#define FF_TURN_FRICTION_V 0.2f

/* 吸引しながらスラロームで曲がるときに、向きの分に足す電圧 [V/(deg/s)]（角速度 1deg/s あたり）。
 * 2026-11-04 のターン調整（モード3 No.1、大回り 90° を 800mm/s・吸引 5.0V）のログ 2 回で、左右の電圧の差の半分を
 * 「角速度の分 + 角加速度の分」に分けると、角速度の分は 0.00041V/(deg/s) だった（2 回とも同じ）。
 * これまでのフィードフォワード（タイヤ 1 つの速さ × FF_SPEED_V_PER_MM_S）は 0.000184V/(deg/s) しかなく、
 * 曲がり始めに角速度が最大 120deg/s 遅れ、それを取り戻そうとして、ターンのあとに 2° 回りすぎていた。
 * 吸引で床に押しつけられて、曲がるときにタイヤが横にこすれる分だと考え、吸引しているときだけ、足りない分を足す
 * （0.00041 − 0.000184 ≒ 0.000225）。角加速度の分は、これまでの値とほぼ同じ（0.000012 と 0.000015）なので変えない */
#define FF_SUCTION_SLALOM_V_PER_DEG_S 0.000225f

/* ---- フィードバック（速さ） ---- */

/* 速さのずれ 1mm/s あたりの電圧 [V/(mm/s)]（P）。
 * 1V で進む速さが KOGUMA（約 340mm/s）の約 3.5 倍なので、KOGUMA の係数を 3.5 で割り、さらに半分から始める */
#define SPEED_KP 0.003f

/* 位置のずれ（速さのずれを足し合わせたもの）1mm あたりの電圧 [V/mm]（I）。決め方は SPEED_KP と同じ */
#define SPEED_KI 0.03f

/* ---- フィードバック（向き） ---- */

/* 角速度のずれ 1deg/s あたりの電圧 [V/(deg/s)]（P）。左右のモーターに、+ と - で逆向きにかける。
 * 2026-10-24 のその場旋回で、目標に約 30deg/s 遅れたままだったので 2 倍にした（0.0015 → 0.003） */
#define OMEGA_KP 0.003f

/* 角度のずれ（角速度のずれを足し合わせたもの）1deg あたりの電圧 [V/deg]（I）。
 * 同じ旋回で、13° ずれても 0.2V にしかならず、摩擦に負けて止まったので、約 3 倍にした（0.015 → 0.05） */
#define ANGLE_KI 0.05f

/* ---- 横の壁に沿って走る補正（直進のときだけ） ---- */

/* 横の壁からのずれ 1 あたり（センサの値の差）、目標の角速度をどれだけ曲げるか [deg/s]（P）。
 * 壁から 1mm 寄るとセンサの値の差が約 290 変わる（2026-10-22 の測定から、おおよその見積もり）ので、
 * 1mm で約 15deg/s 曲げる */
#define WALL_KP 0.05f

/* ずれの変わる速さ 1/s あたり、目標の角速度をどれだけ曲げるか [deg/s]（D）。
 * P だけだと、まん中を通りすぎて左右にゆれ続けるので、ずれが小さくなっていく速さで曲げ方を弱める。
 * 300mm/s で、ゆれが早く収まるように計算した値（減衰比 0.7） */
#define WALL_KD 0.008f

/* 補正で曲げる角速度の上限 [deg/s]。2026-10-24 の探索で、壁の端で読み違えて 90deg/s まで曲げ、
 * 壁に当たったので、45deg/s に下げた */
#define WALL_OMEGA_LIMIT_DEG_S 45.0f

/* これより遅いときは補正しない [mm/s]（止まる直前・走り出しは、センサの値が目標から離れていても気にしない） */
#define WALL_CONTROL_MIN_SPEED_MM_S 100.0f

/* ---- 前壁合わせ（区画のまん中で止まっているとき、前の壁で位置と向きを直す） ---- */

/* 前の壁との距離のずれ 1 あたりの、目標の速さ [mm/s]（近すぎれば下がる）。
 * 前センサの値は、区画のまん中あたりで 1mm に 100 くらい変わる見積もり（仮）なので、1mm のずれで 30mm/s */
#define ALIGN_SPEED_GAIN 0.3f
#define ALIGN_SPEED_LIMIT_MM_S 50.0f  /* 目標の速さの上限 [mm/s]（100 だと U ターンで下がりすぎたので下げた） */

/* 前壁合わせで、合わせ始めた位置から前後に動いてよい距離 [mm]。
 * 区画のまん中で止まっていれば、ずれは数 mm のはずなので、それより大きく動かさない */
#define ALIGN_DISTANCE_LIMIT_MM 5.0f

/* 前の壁に対する向きのずれ 1 あたりの、目標の角速度 [deg/s]（右を向いていれば左へ回す）（仮） */
#define ALIGN_OMEGA_GAIN 0.2f
#define ALIGN_OMEGA_LIMIT_DEG_S 90.0f  /* 目標の角速度の上限 [deg/s] */

/* ---- 止める条件（フェイルセーフ） ---- */

/* 位置のずれがこれより大きくなったら止める [mm]（ぶつかった、タイヤが空回りした、など） */
#define POSITION_ERROR_LIMIT_MM 30.0f

/* 角度のずれがこれより大きくなったら止める [deg]（モーターの向きが逆、ぶつかって向きが変わった、など） */
#define ANGLE_ERROR_LIMIT_DEG 30.0f

/* 速さで見つける異常（KOGUMA_PORTING.md の F2・F3。2026-11-02。値は仮で、実機で決める）。
 * どちらも、当てはまった状態が FAILSAFE_HOLD_MS 続いたら止める（ノイズ 1 回では止めない。F4） */
#define SPEED_DROP_LIMIT_MM_S   300.0f  /* F2：目標の速さより、測った速さがこれ以上遅い（ぶつかった）[mm/s] */
#define STALL_TARGET_MIN_MM_S   200.0f  /* F3：加速も減速もせず、目標の速さがこれ以上で走っているはずなのに… */
#define STALL_SPEED_MAX_MM_S    50.0f   /*     測った速さがこれより遅い（壁を押し続けている）[mm/s] */
#define FAILSAFE_HOLD_MS        10      /* F4：当てはまった状態がこれだけ続いたら止める [ms] */

#endif /* CONFIG_CTRL_GAINS_H */
